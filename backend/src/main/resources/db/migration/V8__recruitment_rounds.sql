CREATE TABLE recruitment_rounds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drive_id BIGINT NOT NULL REFERENCES placement_drives(id) ON DELETE CASCADE,
    name VARCHAR(160) NOT NULL,
    sequence_number INTEGER NOT NULL,
    scheduled_at TIMESTAMPTZ,
    venue VARCHAR(500),
    instructions TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_recruitment_round_drive_sequence
        UNIQUE (drive_id, sequence_number),

    CONSTRAINT chk_recruitment_round_sequence
        CHECK (sequence_number > 0),

    CONSTRAINT chk_recruitment_round_status
        CHECK (status IN ('SCHEDULED', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE recruitment_round_participants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    round_id BIGINT NOT NULL REFERENCES recruitment_rounds(id) ON DELETE CASCADE,
    application_id BIGINT NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
    outcome VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    feedback TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_recruitment_round_application
        UNIQUE (round_id, application_id),

    CONSTRAINT chk_recruitment_round_outcome
        CHECK (outcome IN ('PENDING', 'PASSED', 'FAILED', 'ABSENT'))
);

CREATE INDEX idx_recruitment_rounds_drive
    ON recruitment_rounds(drive_id);

CREATE INDEX idx_round_participants_application
    ON recruitment_round_participants(application_id);